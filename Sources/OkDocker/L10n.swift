enum LanguageSettings {
    static let defaultsKey = "dev.okdocker.language"
    static var code: String {
        UserDefaults.standard.string(forKey: defaultsKey) == "zh" ? "zh" : "en"
    }
    static func set(_ code: String) {
        UserDefaults.standard.set(code == "zh" ? "zh" : "en", forKey: defaultsKey)
    }
}

func tr(_ zh: String) -> String {
    LanguageSettings.code == "zh" ? zh : (Catalog.en[zh] ?? zh)
}

